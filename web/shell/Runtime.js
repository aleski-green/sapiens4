const nullValue = null;
export {nullValue as null};
export const global = globalThis;
export const get = object => key => object?.[key] ?? null;
export const getE = object => key => () => object?.[key] ?? null;
export const defer = action => () => action()();
export const set = object => key => value => () => { object[key] = value; };
export const remove = object => key => () => { delete object[key]; };
export const string = value => String(value ?? '');
export const boolean = value => Boolean(value);
export const number = value => Number(value);
export const int = value => Number(value) | 0;
export const array = value => value == null ? [] : Array.from(value);
export const keys = value => Object.keys(value ?? {});
export const object = entries => Object.fromEntries(entries.map(({key,value}) => [key,value]));
export const merge = values => Object.assign({}, ...values);
export const call = object => key => args => () => Reflect.apply(object[key], object, args);
export const invoke = fn => args => () => Reflect.apply(fn, undefined, args);
export const callback = fn => (...args) => fn(args)();
export const constructible = fn => function(...args) { return fn(args)(); };
export const getter = object => key => action => () => { Object.defineProperty(object, key, {get:action}); };
export const kind = value => typeof value;
export const parseE = source => () => JSON.parse(source);
export const decode64 = source => () => Uint8Array.from(atob(source), c => c.charCodeAt(0));
export const encode64 = bytes => btoa(Array.from(bytes, b => String.fromCharCode(b)).join(''));
export const construct = fn => args => () => Reflect.construct(fn, args);
export const same = a => b => a === b;
export const stringify = value => JSON.stringify(value);
export const pretty = value => JSON.stringify(value, null, 2);
export const parse = source => JSON.parse(source);
export const scope = () => (globalThis.SapiensUI ??= {});
export const children = node => Array.from(node.childNodes ?? []);
export const attributes = node => Array.from(node.attributes ?? [], a => ({key:a.name,value:a.value}));
export const readMarkup = source => () => { const t = document.createElement('template'); t.innerHTML = source; return Array.from(t.content.childNodes); };
export const now = () => Date.now();
export const date = value => new Date(value);
export const dateNumber = value => Date.parse(value);
export const locale = date => method => options => date[method]([], options);
