// Thin bindings to browser APIs. No application state, rendering rules or assertions.
export const window = globalThis.window;
export const document = globalThis.document;
export const root = document?.documentElement;
export const body = document?.body;
export const query = selector => node => () => node.querySelector(selector);
export const queryAll = selector => node => () => Array.from(node.querySelectorAll(selector));
export const closest = selector => node => () => node.closest(selector);
export const attribute = name => node => () => node.getAttribute(name);
export const setAttribute = name => value => node => () => { node.setAttribute(name, value); };
export const removeAttribute = name => node => () => { node.removeAttribute(name); };
export const hasAttribute = name => node => () => node.hasAttribute(name);
export const setText = value => node => () => { node.textContent = value; };
export const text = node => () => node.textContent;
export const setHTML = value => node => () => { node.innerHTML = value; };
export const setProperty = name => value => node => () => { node[name] = value; };
export const property = name => node => () => node[name];
export const setStyle = name => value => node => () => { node.style.setProperty(name, value); };
export const listen = name => capture => handler => node => () => { node.addEventListener(name, event => handler(event)(), capture); };
export const target = event => () => event.target;
export const eventString = name => event => event[name] ?? null;
export const preventDefault = event => () => { event.preventDefault(); };
export const stopImmediatePropagation = event => () => { event.stopImmediatePropagation(); };
export const mediaQuery = value => () => globalThis.matchMedia(value);
export const matches = query => () => query.matches;
export const readStorage = key => () => { try { return localStorage.getItem(key); } catch { return null; } };
export const writeStorage = key => value => () => { try { localStorage.setItem(key, value); } catch {} };
export const expose = key => value => () => { window[key] = value; };
export const global = key => () => window[key] ?? null;
export const createElement = tag => () => document.createElement(tag);
export const appendChildren = children => parent => () => { parent.append(...children); };
export const replaceChildren = children => parent => () => { parent.replaceChildren(...children); };
export const addClass = name => element => () => { element.classList.add(name); };
export const focus = element => () => { element.focus(); };
export const encodeURIComponent = value => globalThis.encodeURIComponent(value);
export const writeClipboard = value => () => navigator.clipboard.writeText(value);
