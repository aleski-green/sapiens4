const render=sandbox.formatText;
let value=render('https://github.com/aleski-green/lab-sapiens-rnd/blob/commit/human_specs/agentpy_spec_human.md');
assert.match(value,/target="_blank"/);assert.match(value,/rel="noopener noreferrer"/);
assert.match(value,/>github.com · agentpy_spec_human.md ↗<\/a>/);
value=render('[Proposal](</Users/Admin/My files/proposal.md>)');
assert.match(value,/data-file-link="\/Users\/Admin\/My files\/proposal.md"/);assert.match(value,/>Proposal<\/button>/);
assert.doesNotMatch(render('@art-md0016 and @art-md0016:old'),/data-artifact-link/);
assert.doesNotMatch(render('@art-md0016:wrong'),/data-artifact-link/);
assert.doesNotMatch(render('@task-x0012 and @create-or-find-one'),/data-task-link/);
assert.doesNotMatch(render('[Bad](javascript:alert(1))'),/<a /);
assert.doesNotMatch(render('<img src=x onerror=alert(1)>'),/<img/);
assert.equal(render('`https://example.com`'),'<code>https://example.com</code>');
assert.match(render('[Reference](https://example.com/docs)'),/>Reference ↗<\/a>/);
assert.match(render('https://example.com/Nova'),/<a /);assert.doesNotMatch(render('https://example.com/Nova'),/<button/);
